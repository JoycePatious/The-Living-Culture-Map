export function getDiscoveryById(id) {
  const numericId = typeof id === 'string' ? parseInt(id, 10) : id;
  return DISCOVERIES_DATA.find((item) => item.id === numericId) || null;
}

export function getStoryById(id) {
  if (!id) return null;
  const lower = String(id).toLowerCase();
  return (
    STORIES_DATA.find(
      (s) =>
        s.id.toLowerCase() === lower ||
        s.title.toLowerCase().includes(lower) ||
        (lower.includes('vadakkumnathan') && s.id === 'architecture') ||
        (lower.includes('pooram') && s.id === 'pooram') ||
        (lower.includes('pulikali') && s.id === 'pulikali')
    ) || null
  );
}

export function getNextDiscovery(currentId) {
  const index = DISCOVERIES_DATA.findIndex((item) => item.id === currentId);
  if (index === -1) return DISCOVERIES_DATA[0];
  const nextIndex = (index + 1) % DISCOVERIES_DATA.length;
  return DISCOVERIES_DATA[nextIndex];
}

export function getPrevDiscovery(currentId) {
  const index = DISCOVERIES_DATA.findIndex((item) => item.id === currentId);
  if (index === -1) return DISCOVERIES_DATA[DISCOVERIES_DATA.length - 1];
  const prevIndex = (index - 1 + DISCOVERIES_DATA.length) % DISCOVERIES_DATA.length;
  return DISCOVERIES_DATA[prevIndex];
}
